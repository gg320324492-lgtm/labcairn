"""The four refusal classes, witnessed against real file operations.

The work order's acceptance is that each class is refused **before any file is
touched**. So each witness here does two things, and the second is the one that
would be skipped: it asserts the loop's named refusal, *and* it arms a
:class:`WriteSpy` over the OS write primitives to assert that no write call was
reached. A refusal that arrives after a file was opened for writing has already
done the thing the refusal forbids.

The files are real: another task's output is a real file on disk; a traversal
target outside the workspace is a real unreadable byte; a stale approval is
made stale by writing real bytes over the original; the duplicate request is
asked a second time against a publication whose bytes are on disk. No mocked
filesystem, no flag that stands in for a write.

Each witness also has its counter-mutation, documented in the acceptance
record: the mutation turns off the one check the witness is about, and the
witness must go red for the property it names rather than for a side effect.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from revision_loop_support import (
    EDITED_BYTES,
    MOMENT,
    ORIGINAL_BYTES,
    LoopFixture,
    WriteSpy,
    build_fixture,
    granted_copy_approval,
    granted_publication_approval,
    open_a_loop,
    refusal_of,
    second_task,
)
from store_support import StoreEnv
from store_support import env as _shared_env

from labcairn.application.refusal import ApplicationRefusal
from labcairn.application.revision_loop import (
    open_loop,
    publish_revision,
    stage_copy,
)
from labcairn.db.repository import list_artifacts
from labcairn.security.approval import content_hash

pytestmark = pytest.mark.negative

env = _shared_env


@pytest.fixture
def fixture(env: StoreEnv, tmp_path: Path) -> LoopFixture:
    return build_fixture(env.store(), tmp_path / "workspace")


# --------------------------------------------------------------------------- #
# 1. cross-project access
# --------------------------------------------------------------------------- #


def test_another_tasks_output_is_not_importable_as_source(fixture: LoopFixture) -> None:
    """A task's generated bytes are not another task's supplied material.

    The second task's output file is real and readable. The declared key names
    it from inside the source root by a parent segment; canonicalisation lands
    it in the output-kind workspace root, and the loop refuses by the class the
    work order names. **The spy is the second half of the assertion**: no write
    primitive was reached, and the foreign file is byte-for-byte what the other
    task wrote.
    """
    other_task_id = second_task(fixture.context.store, fixture)
    foreign = fixture.workspace_root / "output" / str(other_task_id) / "foreign.bin"
    original_foreign = foreign.read_bytes()
    declared = f"../output/{other_task_id}/foreign.bin"

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: open_loop(
                fixture.context,
                source_root_id=fixture.source_root_id,
                source_key=declared,
                now=MOMENT,
            ),
            "a source key that resolves into another task's output area",
        )
    assert error.reason is ApplicationRefusal.CROSS_PROJECT_ACCESS
    assert spy.calls == []
    assert foreign.read_bytes() == original_foreign
    assert fixture.original_path.read_bytes() == ORIGINAL_BYTES


