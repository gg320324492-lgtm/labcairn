# 4. duplicate requests
# --------------------------------------------------------------------------- #


def test_a_spent_approval_cannot_authorise_a_second_copy(fixture: LoopFixture) -> None:
    """One approval, one effect: the second spend has no grant left to spend."""
    loop = open_a_loop(fixture)
    approval_id = granted_copy_approval(fixture.context, loop)
    staged = stage_copy(fixture.context, loop, approval_id=approval_id, now=MOMENT)
    copy_path = fixture.workspace_root / "output" / str(fixture.context.task_id) / loop.copy_key
    assert copy_path.read_bytes() == ORIGINAL_BYTES

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: stage_copy(fixture.context, loop, approval_id=approval_id, now=MOMENT),
            "the same copy approval spent twice",
        )
    assert error.reason is ApplicationRefusal.APPROVAL_REFUSED
    assert "consumed" in str(error)
    assert spy.calls == []
    assert content_hash(copy_path) == staged.copy_sha256


def test_a_second_publication_under_one_id_is_refused_before_the_write(
    fixture: LoopFixture,
) -> None:
    """The duplicate is stopped by its id, not discovered after the bytes land.

    A fresh approval is asked and granted for the second request, so the only
    duplicate is the request itself. The publication's bytes are recorded, a
    marker is appended to a real file outside the loop, and the second call is
    refused with no write primitive reached and with exactly one artefact row
    for the publication id.
    """
    loop = open_a_loop(fixture)
    copy_approval = granted_copy_approval(fixture.context, loop)
    stage_copy(fixture.context, loop, approval_id=copy_approval, now=MOMENT)
    first_approval = granted_publication_approval(fixture.context, loop)
    published = publish_revision(
        fixture.context,
        loop,
        approval_id=first_approval,
        edited_bytes=EDITED_BYTES,
        now=MOMENT,
    )
    publication_path = (
        fixture.workspace_root / "output" / str(fixture.context.task_id) / loop.publication_key
    )
    assert publication_path.read_bytes() == EDITED_BYTES

    second_approval = granted_publication_approval(fixture.context, loop)
    with WriteSpy() as spy:
        error = refusal_of(
            lambda: publish_revision(
                fixture.context,
                loop,
                approval_id=second_approval,
                edited_bytes=b"a second revision under the same id\n",
                now=MOMENT,
            ),
            "a second publication under the same id",
        )
    assert error.reason is ApplicationRefusal.LOOP_ALREADY_PUBLISHED
    assert spy.calls == []
    assert publication_path.read_bytes() == EDITED_BYTES
    assert content_hash(publication_path) == published.publication_sha256
    artifacts = list_artifacts(fixture.context.store.session, fixture.context.task_id)
    assert sum(r.receipt_id == loop.publication_artifact_id for r in artifacts) == 1


# --------------------------------------------------------------------------- #
# the read-only witness, and its counter-mutation
# --------------------------------------------------------------------------- #


def test_a_write_to_the_original_through_the_read_only_door_is_refused(
    fixture: LoopFixture,
) -> None:
    """The loop's own door still refuses a write before any syscall.

    This is the counter-mutation for "the original is unchanged": a source
    that the guard would let be written is the mutation, and the assertion
    below is the same one the integration file makes about the hash. The guard
    refuses and the hash holds; remove the guard's check and both assertions
    turn red.
    """
    import hashlib

    from labcairn.workspace.readonly import SourceIsReadOnlyError, SourceMaterial

    material = SourceMaterial(fixture.context.workspace, fixture.context.policy)
    before = hashlib.sha256(fixture.original_path.read_bytes()).hexdigest()
    with WriteSpy() as spy, pytest.raises(SourceIsReadOnlyError):
        material.write("original.bin", b"overwritten\n", root_id=fixture.source_root_id)
    assert spy.calls == []
    assert fixture.original_path.read_bytes() == ORIGINAL_BYTES
    assert content_hash(fixture.original_path) == before
