# 2. path escape
# --------------------------------------------------------------------------- #


def test_a_traversal_out_of_the_workspace_is_refused_before_any_write(
    fixture: LoopFixture,
) -> None:
    """The canonicaliser's ``outside_every_root`` becomes the loop's refusal.

    The target is a real file outside the selected workspace: if the loop
    joined paths without canonicalising, this witness would read it. The spy
    proves nothing was written either, and the outside file's own bytes say it
    was not opened for writing.
    """
    outside = fixture.workspace_root.parent / "outside-the-workspace.bin"
    outside.write_bytes(b"outside bytes\n")
    declared = "../../outside-the-workspace.bin"

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: open_loop(
                fixture.context,
                source_root_id=fixture.source_root_id,
                source_key=declared,
                now=MOMENT,
            ),
            "a source key that escapes the selected root",
        )
    assert error.reason is ApplicationRefusal.PATH_REFUSED
    assert spy.calls == []
    assert outside.read_bytes() == b"outside bytes\n"


def test_an_existing_original_outside_the_bound_source_root_is_refused(
    fixture: LoopFixture,
) -> None:
    """A spelling that names a real file in the workspace but outside the source root.

    The file exists — the refusal is not "not found". It is that the loop's
    import names one root, and a key that resolves into a different one is not
    the material that root holds.
    """
    loose = fixture.workspace_root / "loose.bin"
    loose.write_bytes(b"real file, wrong root\n")

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: open_loop(
                fixture.context,
                source_root_id=fixture.source_root_id,
                source_key="../loose.bin",
                now=MOMENT,
            ),
            "a source key that lands in another root",
        )
    assert error.reason is ApplicationRefusal.PATH_REFUSED
    assert spy.calls == []
    assert loose.read_bytes() == b"real file, wrong root\n"


# --------------------------------------------------------------------------- #
# 3. stale approval
# --------------------------------------------------------------------------- #


def test_an_original_moved_after_the_grant_is_refused_before_the_copy(
    fixture: LoopFixture,
) -> None:
    """The staleness is about material, and the ledger's re-hash says so.

    The approval's window is still open (the grant and the use are at the same
    fixed moment), so the only thing that went stale is the file. The grant's
    ``bound_sources`` carries the original's hash; writing real bytes over the
    original makes the re-hash disagree; the spend reports ``source_changed``.
    **The copy file does not exist afterwards** — the refusal happened before
    the write, and the spy says no write primitive was reached.
    """
    loop = open_a_loop(fixture)
    requested = fixture.context.ledger.peek(granted_copy_approval(fixture.context, loop))
    assert requested is not None
    assert requested.sources[0].expected_hash == loop.import_receipt.original_sha256

    approval_id = requested.approval_id
    fixture.original_path.write_bytes(ORIGINAL_BYTES + b"tampered\n")
    copy_path = fixture.workspace_root / "output" / str(fixture.context.task_id) / loop.copy_key

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: stage_copy(fixture.context, loop, approval_id=approval_id, now=MOMENT),
            "an approval whose original moved after the grant",
        )
    assert error.reason is ApplicationRefusal.APPROVAL_REFUSED
    assert "source_changed" in str(error)
    assert spy.calls == []
    assert not copy_path.exists()


def test_an_original_moved_after_the_import_is_refused_at_publish(
    fixture: LoopFixture,
) -> None:
    """The publish-time guard compares the original against the import receipt."""
    loop = open_a_loop(fixture)
    copy_approval = granted_copy_approval(fixture.context, loop)
    stage_copy(fixture.context, loop, approval_id=copy_approval, now=MOMENT)
    publication_approval = granted_publication_approval(fixture.context, loop)
    fixture.original_path.write_bytes(b"edited by someone else\n")
    publication_path = (
        fixture.workspace_root / "output" / str(fixture.context.task_id) / loop.publication_key
    )

    with WriteSpy() as spy:
        error = refusal_of(
            lambda: publish_revision(
                fixture.context,
                loop,
                approval_id=publication_approval,
                edited_bytes=EDITED_BYTES,
                now=MOMENT,
            ),
            "a publication whose original drifted after the import",
        )
    assert error.reason is ApplicationRefusal.APPROVAL_REFUSED
    assert "source_changed" in str(error)
    assert spy.calls == []
    assert not publication_path.exists()


