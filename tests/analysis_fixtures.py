"""LC-P1-10's corpus: the fixtures, their expected values, and how to write them.

What this module is for
-----------------------
LC-P1-10's operators will read tabular material, and a corpus is the only
honest way to know whether they compute what they claim. Three things live
here, and the three are deliberately separate:

* **the fixtures** — ``tests/fixtures/analysis/*.csv``, committed as text;
* **the expected values** — a companion ``*.expected.json`` per fixture, also
  committed, and *not* generated by anything in this repository;
* **the writers** — the one place that knows how to turn a table into CSV or
  into a spreadsheet.

The separation is the point. An expectation that lives inside the test can be
corrupted by the same bug that breaks the code; an expectation that lives in a
data file cannot, and a change to the operators that alters a result fails a
test rather than silently rewriting a golden file. **No script in this
repository regenerates the ``*.expected.json`` files**, and that is the
property worth keeping.

The spreadsheet fixtures are generated rather than committed
------------------------------------------------------------
A ``.xlsx`` is a binary blob: a reviewer cannot read it, and a reviewer who
cannot read it cannot tell whether it says what the corpus claims. So the
spreadsheets are *derived* — ``build_spreadsheet_fixtures`` turns a CSV
fixture into the same table in the other format — and the test asserts what
the result contains. The generator is here rather than in the corpus
directory so that the CSV reader, the CSV writer and the spreadsheet writer
cannot drift apart: there is one implementation of "a table", not three.

**The cells are written as the CSV's own text, not re-typed as numbers.**
That is what makes the two paths comparable. If the spreadsheet held real
numbers, ``1`` would arrive as the float ``1.0`` and render as ``"1.0"``
while the CSV's cell reads ``"1"``, and every difference between the two
paths would be the writer's rather than the adapter's. Written as text, the
two paths carry the same characters, and any difference between them is the
adapter's — which is the thing the corpus exists to measure.

What the corpus is not
----------------------
It is not a test of the operators. They do not exist yet (LC-P1-10 T04 and
T05), and this module is what they will be tested against. What this module
*does* assert is that the corpus is internally honest: that the fixtures
ingest to the cells the expected files describe, and that the statistics in
the expected files are the statistics of the data.
"""

from __future__ import annotations

import csv
import io
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

__all__ = [
    "CORPUS_DIR",
    "FIXTURE_NAMES",
    "SPREADSHEET_SOURCES",
    "Table",
    "build_spreadsheet_fixtures",
    "corpus_cells",
    "corpus_selection",
    "corpus_source",
    "expected_path",
    "load_expected",
    "read_table_csv",
    "row_numbers",
    "write_table_csv",
    "write_table_xlsx",
]

#: Where the corpus lives.
CORPUS_DIR: Final[Path] = Path(__file__).resolve().parent / "fixtures" / "analysis"

#: Every committed fixture, by file name. The spreadsheets are absent on
#: purpose: they are derived, and a derived file is not a fixture.
FIXTURE_NAMES: Final[tuple[str, ...]] = (
    "basic.csv",
    "empty.csv",
    "groups.csv",
    "holes.csv",
    "missing.csv",
    "single.csv",
    "typed.csv",
    "units.csv",
)

#: Which CSV each derived spreadsheet comes from. The names are the point:
#: ``numeric.xlsx`` is ``basic.csv`` in the other format, and ``holes.xlsx``
#: is ``holes.csv`` — the table with one emptied cell — in the other format.
#: Reading the two pairs together is how the corpus shows what the two
#: adapters do with an empty cell.
SPREADSHEET_SOURCES: Final[dict[str, str]] = {
    "numeric.xlsx": "basic.csv",
    "holes.xlsx": "holes.csv",
}

#: The sheet name the derived spreadsheets carry. One name, so the two
#: spreadsheets differ only in their data and never in their addressing.
SHEET_NAME: Final[str] = "Trial"


@dataclass(frozen=True, slots=True)
class Table:
    """A table of text: a header row and the rows under it.

    Every value is a **string**, because that is what both adapters hold:
    ``source_texts`` stores the text the file held, and a number is a
    rendering of a string rather than a different kind of thing. Holding the
    text is what lets a cell's quantity be a *reading* of it.
    """

    headers: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]

    def cell(self, row: int, column: str) -> str | None:
        """The text at one cell, or ``None`` when the row has no such field.

        ``row`` is 0-based over ``rows`` — the data rows, not the physical
        lines of the file. A short row is not an error here; the adapter
        reports it, and the corpus records which cells exist.
        """
        if not 0 <= row < len(self.rows):
            return None
        fields = self.rows[row]
        try:
            index = self.headers.index(column)
        except ValueError:
            return None
        if index >= len(fields):
            return None
        return fields[index]


def read_table_csv(data: bytes) -> Table:
    """Read a CSV into a table, faithfully.

    The stdlib reader, because the corpus's CSVs are plain: no quoting, one
    delimiter, no embedded newlines. A fixture that needed more than this
    would be a fixture about the *reader* rather than about the operators,
    and it belongs in a test of the adapter.
    """
    text = data.decode("utf-8")
    reader = csv.reader(io.StringIO(text, newline=""))
    records = list(reader)
    if not records:
        return Table(headers=(), rows=())
    return Table(headers=tuple(records[0]), rows=tuple(tuple(r) for r in records[1:]))


def write_table_csv(table: Table) -> bytes:
    """Render a table as CSV bytes.

    Used to check that a committed fixture is in the canonical form this
    corpus writes — the same check the two spreadsheet fixtures get, applied
    to the text ones.
    """
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(table.headers)
    for row in table.rows:
        writer.writerow(row)
    return buffer.getvalue().encode("utf-8")


def write_table_xlsx(table: Table, *, sheet_name: str = SHEET_NAME) -> bytes:
    """Render a table as spreadsheet bytes.

    Every cell is written as **text**, for the reason in the module
    docstring: the spreadsheet must carry the same characters as the CSV, so
    that a difference between the two paths is the adapter's and not the
    writer's.

    An empty field is written as an empty cell, which the spreadsheet adapter
    does not extract — that is the asymmetry the corpus is built to show,
    and it is a property of the *adapter*, not of this writer.
    """
    import openpyxl

    workbook = openpyxl.Workbook()
    sheet = workbook.active
    if sheet is None:  # pragma: no cover - openpyxl always has one
        msg = "openpyxl returned a workbook with no active sheet"
        raise RuntimeError(msg)
    sheet.title = sheet_name
    for index, header in enumerate(table.headers, start=1):
        sheet.cell(row=1, column=index, value=header)
    for row_index, row in enumerate(table.rows, start=2):
        for column_index, value in enumerate(row, start=1):
            sheet.cell(row=row_index, column=column_index, value=value)
    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


def build_spreadsheet_fixtures() -> dict[str, bytes]:
    """The derived spreadsheets, by file name.

    Each one is the table of a committed CSV, in the other format. The
    mapping is :data:`SPREADSHEET_SOURCES`, so the pairing is data rather
    than a convention someone has to remember.
    """
    built: dict[str, bytes] = {}
    for name, source in SPREADSHEET_SOURCES.items():
        table = read_table_csv((CORPUS_DIR / source).read_bytes())
        built[name] = write_table_xlsx(table)
    return built


def expected_path(fixture: str) -> Path:
    """Where the expected values for one fixture live.

    The **whole** file name, not its stem: ``holes.csv`` and ``holes.xlsx``
    are two fixtures of the same table, and a stem-named file would have one
    of them overwrite the other.
    """
    return CORPUS_DIR / f"{fixture}.expected.json"


def corpus_cells(fixture: str) -> dict[tuple[int, str], str]:
    """The cells of one corpus fixture, addressed by (physical row, header text).

    Read through the **real** ingestion path, so that what the corpus says
    about a fixture and what the adapters make of it are the same statement.

    The address is the corpus's own: a physical row and a column's **header
    text**. A spreadsheet's header row is included, because A1 and B1 are
    cells like any other; a CSV's is not, because the CSV adapter takes row 1
    as the header and extracts no cells from it. The data rows of both formats
    are the physical rows from 2 upwards.
    """
    import datetime as dt

    from labcairn.material.ingest import ingest_bytes
    from labcairn.sources.locators import CsvLocator, XlsxLocator

    now = dt.datetime(2026, 10, 19, tzinfo=dt.UTC)
    if fixture in SPREADSHEET_SOURCES:
        data = build_spreadsheet_fixtures()[fixture]
    else:
        data = (CORPUS_DIR / fixture).read_bytes()

    material = ingest_bytes(data, relative_path=fixture, display_name=fixture, ingested_at=now)
    cells: dict[tuple[int, str], str] = {}
    if fixture.endswith(".csv"):
        for text in material.texts:
            locator = text.locator
            if not isinstance(locator, CsvLocator):
                msg = f"{fixture} produced a {type(locator).__name__}, which is not a CSV locator"
                raise AssertionError(msg)
            cells[(locator.row, locator.column)] = text.text
        return cells

    by_ref: dict[str, tuple[int, str]] = {}
    for text in material.texts:
        locator = text.locator
        if not isinstance(locator, XlsxLocator):
            msg = (
                f"{fixture} produced a {type(locator).__name__}, which is not a spreadsheet locator"
            )
            raise AssertionError(msg)
        row = int("".join(ch for ch in locator.cell_ref if ch.isdigit()))
        by_ref[locator.cell_ref] = (row, text.text)
    header_by_letter = {
        "".join(ch for ch in ref if ch.isalpha()): value
        for ref, (row, value) in by_ref.items()
        if row == 1
    }
    for ref, (row, value) in by_ref.items():
        header = header_by_letter.get("".join(ch for ch in ref if ch.isalpha()))
        if header is not None:
            cells[(row, header)] = value
    return cells


def load_expected(fixture: str) -> dict[str, Any]:
    """The expected values for one fixture, parsed."""
    path = expected_path(fixture)
    if not path.is_file():
        msg = f"no expected values for {fixture!r}: {path} does not exist"
        raise FileNotFoundError(msg)
    parsed: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return parsed


def row_numbers(spec: Any) -> list[int]:
    """The physical rows a selection names.

    The corpus's vocabulary: a range string like ``"2-11"`` for a contiguous
    run, or a list of row numbers. Both spellings appear in the expected
    files, and a reader that knew only one of them would silently read the
    other as nothing.
    """
    if isinstance(spec, str):
        start, _, end = spec.partition("-")
        return list(range(int(start), int(end) + 1))
    return [int(r) for r in spec]


class CorpusSource:
    """A cell source over one corpus fixture, read through the real adapters.

    The corpus's own reader, so the selection's behaviour is checked against
    the same cells the expected values describe.
    """

    def __init__(self, fixture: str) -> None:

        self._cells = corpus_cells(fixture)
        self._rows = tuple(sorted({row for row, _ in self._cells}))
        from labcairn.analysis.values import records_blank_cells
        from labcairn.sources.source import SourceKind

        kind = SourceKind.CSV if fixture.endswith(".csv") else SourceKind.XLSX
        self._records_blank = records_blank_cells(kind)

    def text_at(self, address: Any) -> str | None:
        return self._cells.get((address.row, address.column))

    def rows(self) -> tuple[int, ...]:
        return self._rows

    @property
    def records_blank_cells(self) -> bool:
        return self._records_blank


def corpus_source(fixture: str) -> CorpusSource:
    """A cell source over one corpus fixture."""
    return CorpusSource(fixture)


def corpus_selection(fixture: str, described: Any) -> Any:
    """The selection an expected file describes.

    The corpus's vocabulary: a range string like ``"2-11"`` for a contiguous
    run, or a list of row numbers, and the columns by header text.
    """
    from labcairn.analysis.selection import MissingPolicy, RowRange, RowSet, Selection

    rows = row_numbers(described["rows"])
    return Selection(
        source_id=fixture,
        content_sha256="a" * 64,
        columns=tuple(described["columns"]),
        rows=RowRange(rows[0], rows[-1]) if len(rows) > 1 else RowSet(tuple(rows)),
        missing=MissingPolicy.EXCLUDE,
    )
