"""The corpus measurement: cells read exactly as the committed key says.

**What this measures, and why it is not a test pass rate.** The protocol
asks for *"numeric-cell extraction exactness and unit consistency"*. A
count of green tests would answer a different question — it would say how
many checks passed, not how many cells the product read correctly. So this
module measures the thing the protocol names: it takes the committed
answer key beside the corpus (``tests/fixtures/analysis/*.expected.json``),
runs the product's **own** selection code over the same cells, and compares
**cell by cell**.

The answer key is the right judge because of what it is: it was written by
hand beside the data, it is not generated by anything in this repository,
and its statistics were computed with Python's :mod:`statistics` — an
implementation that is not LabCairn's. So the comparison is a comparison
and not an echo.

**What the unit of measurement is, stated plainly.** The protocol says
*cell*; the key is written at the granularity of a **selection** plus the
per-cell classification of that selection's cells. So the unit here is the
cell — the key names each cell that is absent, each that is empty and each
that holds something that is not a number, and everything else it addresses
is a quantity — and the denominator is the number of cells the key
addresses. The report says this in the metric's own ``how`` line, because a
denominator whose unit is unstated is not a transparent denominator.

**Nothing is re-implemented here.** The two refusal points are the
product's own:

* a column whose **header** declares a unit the cells contradict is refused
  by :func:`labcairn.analysis.selection.resolve_selection`;
* a selection whose **cells** carry two unit tokens is refused by the
  operator, which is where the corpus says it is refused.

This module calls both and reports what they did. It does not have a rule
of its own for when a selection counts as refused, because a second
implementation of that rule would be a second answer to the same question.

**A measurement that cannot be made is reported as such.** If the corpus
cannot be read, or a selection cannot be resolved, the selection is
recorded as a **failure case** and its cells count as not exact. The
measurement never quietly shrinks its own denominator to make the rate look
better.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Final

from analysis_fixtures import (
    FIXTURE_NAMES,
    SPREADSHEET_SOURCES,
    corpus_selection,
    corpus_source,
    load_expected,
)

from .model import Measurement

#: Every fixture the corpus holds: the committed CSVs and the derived
#: spreadsheets.
CORPUS_FIXTURES: Final[tuple[str, ...]] = FIXTURE_NAMES + tuple(sorted(SPREADSHEET_SOURCES))

#: The outcome names the answer key uses, mapped to the product's own
#: ``CellOutcome`` members. The key names a cell's kind with a string and
#: the product names it with an enum, and this table is the only place the
#: two vocabularies meet.
KEY_OUTCOMES: Final[dict[str, str]] = {
    "absent": "ABSENT",
    "empty": "EMPTY",
    "not_a_quantity": "NOT_A_QUANTITY",
}

#: The outcome a cell has when the answer key does not name it: it is a
#: quantity. Every addressed cell is one of the four kinds, and the key
#: names only the three that are not quantities.
DEFAULT_OUTCOME: Final = "VALUE"


@dataclass(frozen=True, slots=True)
class CorpusMeasurement:
    """What the corpus measurement produced."""

    #: The cells the answer key addresses — the denominator of exactness.
    cells_addressed: int
    #: The cells the product read exactly as the key says.
    cells_exact: int
    #: The addressed cells the key says carry a quantity.
    quantity_cells: int
    #: Of those, the ones the product read as a quantity.
    quantity_cells_exact: int
    #: The selections whose unit expectation the key states.
    selections_with_units: int
    #: The selections whose unit the product reported consistently.
    selections_unit_consistent: int
    #: The selections the key says must be refused.
    refusals_expected: int
    #: The selections the product refused, as the key expects.
    refusals_correct: int
    #: What did not match, one line per selection.
    failures: tuple[str, ...] = ()
    #: Why the measurement could not be made at all.
    error: str = ""

    @property
    def exactness(self) -> Measurement:
        """The exactness measurement, with its denominator."""
        return Measurement(
            status="MEASURED",
            numerator=self.cells_exact,
            denominator=self.cells_addressed,
            how=(
                "the cells the committed answer key addresses, compared cell by "
                "cell against the classification the product's own selection "
                "code gives them (a quantity, an empty cell, an absent cell, "
                "or text that is not a number)"
            ),
        )

    @property
    def quantity_extraction(self) -> Measurement:
        """The quantity-extraction measurement.

        **Why it is a second number.** The exactness figure counts every
        addressed cell, including the ones the key says are empty, absent
        or not a number — reading a cell as *empty* is a correct reading.
        This figure counts only the cells that carry a quantity, so it is
        the narrower claim the protocol's word *"numeric-cell"* makes. Both
        are reported, and neither stands in for the other.
        """
        return Measurement(
            status="MEASURED",
            numerator=self.quantity_cells_exact,
            denominator=self.quantity_cells,
            how=(
                "the addressed cells the answer key says carry a quantity, "
                "compared against the cells the product read as a quantity"
            ),
        )

    @property
    def unit_consistency(self) -> Measurement:
        """The unit-consistency measurement, with its denominator."""
        return Measurement(
            status="MEASURED",
            numerator=self.selections_unit_consistent,
            denominator=self.selections_with_units,
            how=(
                "the selections whose answer key states a unit, checked "
                "against the distinct unit tokens the product's own selection "
                "code reports for the cells it used"
            ),
        )


def _row_numbers(spec: object) -> list[int]:
    """The physical rows a selection's ``rows`` names.

    The corpus's vocabulary: a range string like ``"2-11"``, or a list of
    row numbers. Both spellings appear in the committed key, and a reader
    that knew only one of them would read the other as nothing — which
    would silently shrink the denominator.
    """
    if isinstance(spec, str):
        start, _, end = spec.partition("-")
        return list(range(int(start), int(end) + 1))
    if isinstance(spec, list):
        return [int(row) for row in spec]
    msg = f"the answer key's rows are in a shape this reader does not know: {spec!r}"
    raise ValueError(msg)


def _key_classifications(described: dict[str, object]) -> dict[tuple[int, str], str]:
    """The answer key's per-cell classification of one selection."""
    expected = described.get("expect")
    if not isinstance(expected, dict):
        return {}
    classifications: dict[tuple[int, str], str] = {}
    for key_name, outcome in KEY_OUTCOMES.items():
        entries = expected.get(key_name)
        if not isinstance(entries, list):
            continue
        for entry in entries:
            row, column = entry
            classifications[(int(row), str(column))] = outcome
    return classifications


def _expected_unit(described: dict[str, object]) -> str | None:
    """The unit the answer key states for a selection."""
    expected = described.get("expect")
    if not isinstance(expected, dict):
        return None
    unit = expected.get("unit")
    return None if unit is None else str(unit)


def measure_corpus(repo_root: Path) -> CorpusMeasurement:
    """Measure the corpus against the committed answer key."""
    from labcairn.analysis.operators.descriptive import DescriptiveArgs, mean
    from labcairn.analysis.selection import SelectionRefusedError, resolve_selection
    from labcairn.analysis.units import UnitDisagreementError

    cells_addressed = 0
    cells_exact = 0
    quantity_cells = 0
    quantity_cells_exact = 0
    selections_with_units = 0
    selections_unit_consistent = 0
    refusals_expected = 0
    refusals_correct = 0
    failures: list[str] = []

    for fixture in CORPUS_FIXTURES:
        key = repo_root / "tests" / "fixtures" / "analysis" / f"{fixture}.expected.json"
        if not key.is_file():
            failures.append(f"{fixture}: the answer key is not in the tree")
            continue
        payload = load_expected(fixture)
        selections = payload.get("selections")
        if not isinstance(selections, list):
            failures.append(f"{fixture}: the answer key names no selection")
            continue
        source = corpus_source(fixture)
        for described in selections:
            if not isinstance(described, dict):
                continue
            rows = _row_numbers(described["rows"])
            columns = [str(column) for column in described["columns"]]
            addressed = {(row, column) for row in rows for column in columns}
            expected = described.get("expect")
            expected_outcome = expected.get("outcome") if isinstance(expected, dict) else None
            selection = corpus_selection(fixture, described)

            refused = False
            result = None
            try:
                result = resolve_selection(selection, source)
            except (UnitDisagreementError, SelectionRefusedError):
                refused = True
            if not refused:
                try:
                    mean(DescriptiveArgs(selection=selection), source)
                except (UnitDisagreementError, SelectionRefusedError):
                    refused = True

            if expected_outcome == "refused":
                refusals_expected += 1
                if refused:
                    refusals_correct += 1
                else:
                    failures.append(
                        f"{fixture}: the key says this selection must be refused, "
                        "and the product did not refuse it"
                    )
                continue

            if refused:
                cells_addressed += len(addressed)
                failures.append(
                    f"{fixture}: the key says this selection resolves, and the product refused it"
                )
                continue

            if result is None:  # pragma: no cover - refused is set with it
                failures.append(f"{fixture}: the selection produced no result")
                continue

            classifications = _key_classifications(described)
            product = {
                (cell.address.row, cell.address.column): cell.outcome.name for cell in result.cells
            }
            exact = 0
            for address in addressed:
                wanted = classifications.get(address, DEFAULT_OUTCOME)
                if product.get(address) == wanted:
                    exact += 1
            cells_addressed += len(addressed)
            cells_exact += exact
            quantity_cells += len(addressed) - len(classifications)
            quantity_cells_exact += sum(
                1
                for address in addressed
                if address not in classifications and product.get(address) == DEFAULT_OUTCOME
            )
            if exact != len(addressed):
                wrong = sorted(
                    address
                    for address in addressed
                    if product.get(address) != classifications.get(address, DEFAULT_OUTCOME)
                )
                failures.append(
                    f"{fixture}: {len(addressed) - exact} of {len(addressed)} "
                    f"addressed cells were not read as the key says: {wrong[:5]}"
                )

            selections_with_units += 1
            expected_unit = _expected_unit(described)
            wanted_units = () if expected_unit is None else (expected_unit,)
            if tuple(result.units) == wanted_units:
                selections_unit_consistent += 1
            else:
                failures.append(
                    f"{fixture}: the key says the unit is {expected_unit!r} and the "
                    f"product reported {tuple(result.units)!r}"
                )

    return CorpusMeasurement(
        cells_addressed=cells_addressed,
        cells_exact=cells_exact,
        quantity_cells=quantity_cells,
        quantity_cells_exact=quantity_cells_exact,
        selections_with_units=selections_with_units,
        selections_unit_consistent=selections_unit_consistent,
        refusals_expected=refusals_expected,
        refusals_correct=refusals_correct,
        failures=tuple(failures),
    )
