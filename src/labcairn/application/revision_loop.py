def _admit_source(
    context: ApplicationContext, *, source_root_id: str, source_key: str
) -> CanonicalPath:
    """Resolve a source key into its canonical path, or refuse with the class named.

    The classification happens **by what the filesystem says the key names**,
    not by pattern-matching the caller's spelling:

    * it resolves into an **output-kind root** (a task's output area, or the
      workspace root itself) → ``cross_project_access``: those areas hold
      generated bytes. Treating generated bytes as supplied material makes one
      task's output another task's input, and the read-only-original guarantee
      only says anything about material the researcher supplied;
    * it resolves into the **named source root** → admitted, and the normal
      read-only path continues;
    * it resolves into *no* bound root, or its spelling is one canonicalisation
      rejects → ``path_refused``, the layer's existing path class.
    """
    try:
        root = context.workspace.root_for(source_root_id)
    except WorkspaceError as error:
        raise ApplicationRefusedError(
            ApplicationRefusal.PATH_REFUSED,
            f"the workspace binds no root {source_root_id!r}: {error}",
        ) from error

    declared = root.path.joinpath(*source_key.split("/"))
    try:
        canonical = context.workspace.canonicalize(declared)
    except WorkspaceError as error:
        raise ApplicationRefusedError(
            ApplicationRefusal.PATH_REFUSED,
            f"the source key {source_key!r} was refused: {error}. A source key is a "
            "path inside a bound source root; a spelling that escapes it is a deny, "
            "not an ask.",
        ) from error

    if canonical.root_id != source_root_id:
        landed = context.workspace.root_for(canonical.root_id)
        if landed.kind is RootKind.OUTPUT:
            raise ApplicationRefusedError(
                ApplicationRefusal.CROSS_PROJECT_ACCESS,
                f"the source key {source_key!r} resolves into {canonical.root_id!r}, an "
                "output area holding generated bytes. A task's outputs are that task's "
                "generated bytes, not supplied material: importing one task's output "
                "as a source makes the output an input and joins two projects' ledgers "
                "under one task's name.",
            )
        raise ApplicationRefusedError(
            ApplicationRefusal.PATH_REFUSED,
            f"the source key {source_key!r} resolved into root {canonical.root_id!r}, "
            f"but {source_root_id!r} was required.",
        )
    return context.workspace.canonicalize_in(declared, source_root_id)


def open_loop(
    context: ApplicationContext,
    *,
    source_root_id: str,
    source_key: str,
    now: datetime | None = None,
) -> LoopOpened:
    """Import one original and open the revision loop that carries it.

    The read is :meth:`SourceMaterial.read_permitted` — the door that applies
    the policy to the file and keeps the source read-only by construction —
    and the import receipt is written beside it: the manifest names the hash,
    and the artefact row is what a reader audits rather than the manifest's
    prose.

    :raises ApplicationRefusedError: the key names an output area
        (``cross_project_access``), escapes every bound root (``path_refused``),
        or the policy denied reading the material (``permission_denied``).
    """
    moment = now if now is not None else datetime.now(UTC)
    canonical = _admit_source(context, source_root_id=source_root_id, source_key=source_key)

    material = SourceMaterial(context.workspace, context.policy)
    try:
        data = material.read_permitted(
            source_key,
            root_id=source_root_id,
            capability=CapabilityId.SOURCE_READ.value,
        )
    except PermissionError as error:
        raise ApplicationRefusedError(
            ApplicationRefusal.PERMISSION_DENIED,
            f"the policy denied reading the source {source_key!r}: {error}",
        ) from error

    original_sha256 = content_hash(canonical.real_path)
    relative_path = canonical.real_path.relative_to(context.workspace.selected_root).as_posix()
    source_id = str(new_id())

    # The ledger row and the binding: the material exists in the ledger, and
    # the task *holds* it. ``put_source`` is the same writer the walk uses, so
    # a loop's material and a walk's material are one kind of row.
    ingested = ingest_bytes(
        data,
        relative_path=relative_path,
        display_name=relative_path.rsplit("/", 1)[-1],
        ingested_at=moment,
        source_id=source_id,
    )
    with store_refusals():
        put_source(context.store.session, ingested.source)
        context.store.session.commit()
    _bind_one(context, SourceId(source_id), moment)

    receipt_id = str(new_id())
    loop = LoopOpened(
        import_receipt=ImportReceipt(
            receipt_id=receipt_id,
            task_id=str(context.task_id),
            source_id=source_id,
            source_root_id=source_root_id,
            source_key=canonical.resolved_key,
            relative_path=relative_path,
            original_sha256=original_sha256,
            size_bytes=len(data),
            imported_at=moment,
        ),
        copy_key=f"{LOOP_DIR_NAME}/{receipt_id}/copy.bin",
        publication_key=f"{LOOP_DIR_NAME}/{receipt_id}/published.bin",
        manifest_key=f"{LOOP_DIR_NAME}/{receipt_id}/import-receipt.json",
        publication_artifact_id=str(new_id()),
        import_artifact_id=str(new_id()),
    )

    manifest = json.dumps(
        loop.import_receipt.model_dump(mode="json"), sort_keys=True, ensure_ascii=False
    ).encode()
    written = TaskOutputArea(context.workspace).write(loop.manifest_key, manifest)

    import_artifact = ArtifactReceipt(
        receipt_id=loop.import_artifact_id,
        task_id=str(context.task_id),
        kind=ArtifactKind.MANIFEST,
        relative_path=written.absolute_path.relative_to(context.workspace.selected_root).as_posix(),
        content_sha256=written.content_hash,
        size_bytes=written.size_bytes,
        produced_by=ArtifactProducerKind.STAGE,
        producer_id=LOOP_PRODUCER_ID,
        derived_from=(
            DerivationRef(
                target_kind=DerivationTargetKind.MATERIAL_FILE,
                target_id=relative_path,
                content_sha256=original_sha256,
            ),
        ),
        media_type="application/json",
        created_at=moment,
    )
    with context.store.unit(context.task_id) as work_unit:
        work_unit.put_artifact(import_artifact)
        work_unit.emit(EventType.ARTIFACT_RECORDED, occurred_at=moment)
    return loop


def _bind_one(context: ApplicationContext, source_id: SourceId, moment: datetime) -> None:
    """Add one source to what the task holds, keeping the task's own order."""
    with store_refusals():
        held = load_task(context.store.session, context.task_id).bound_source_ids
    if source_id in held:
        return
    with store_refusals():
        context.store.bind_sources(context.task_id, (*held, source_id), occurred_at=moment)


