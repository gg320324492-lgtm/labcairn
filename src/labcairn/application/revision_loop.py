def publish_revision(
    context: ApplicationContext,
    loop: LoopOpened,
    *,
    approval_id: ApprovalId,
    edited_bytes: bytes,
    run_id: RunId | None = None,
    now: datetime | None = None,
) -> RevisionPublished:
    """Publish the edited bytes as the loop's revision, and record the receipt.

    **The duplicate check runs before the write, not after.** A publication id
    that already carries a receipt is refused as ``loop_already_published``
    without opening anything: "the same request twice" is a fact about the
    request, and a loop that discovered the duplicate only after landing the
    bytes would have done the thing the refusal forbids.

    **The original is re-hashed inside the authorised effect.** The
    publication's derivation names the original's hash; recording it against
    bytes that no longer match would be a provenance claim the filesystem
    contradicts.

    :raises ApplicationRefusedError: ``loop_already_published``,
        ``source_drifted``, an approval that does not cover this write, or a
        refused write.
    """
    moment = now if now is not None else datetime.now(UTC)
    with store_refusals():
        landed = list_artifacts(context.store.session, context.task_id)
    if any(receipt.receipt_id == loop.publication_artifact_id for receipt in landed):
        raise ApplicationRefusedError(
            ApplicationRefusal.LOOP_ALREADY_PUBLISHED,
            f"the loop {loop.import_receipt.receipt_id!r} has already published "
            f"(publication id {loop.publication_artifact_id}). A second publication "
            "under the same id is the duplicate request refused by name. To publish a "
            "further revision, import the new bytes as a new loop — its import receipt "
            "is what makes a revision a distinct one.",
        )

    def publish_work(resource: CanonicalPath) -> StageOutcome:
        del resource  # the authorised resource is the publication's own key
        verify_original(context, loop)
        written = TaskOutputArea(context.workspace).write(loop.publication_key, edited_bytes)
        publication = ArtifactReceipt(
            receipt_id=loop.publication_artifact_id,
            task_id=str(context.task_id),
            kind=ArtifactKind.OTHER,
            relative_path=written.absolute_path.relative_to(
                context.workspace.selected_root
            ).as_posix(),
            content_sha256=written.content_hash,
            size_bytes=written.size_bytes,
            produced_by=ArtifactProducerKind.STAGE,
            producer_id=LOOP_PRODUCER_ID,
            derived_from=(
                DerivationRef(
                    target_kind=DerivationTargetKind.MATERIAL_FILE,
                    target_id=loop.import_receipt.relative_path,
                    content_sha256=loop.import_receipt.original_sha256,
                ),
                DerivationRef(
                    target_kind=DerivationTargetKind.ARTIFACT,
                    target_id=loop.import_artifact_id,
                    content_sha256=_import_receipt_hash(context, loop),
                ),
            ),
            created_at=moment,
        )
        return StageOutcome(output_hashes=(written.content_hash,), artifacts=(publication,))

    stage_run = run_stage(
        context,
        _stage_request(
            loop, stage_name=PUBLICATION_STAGE_NAME, approval_id=approval_id, run_id=run_id
        ),
        publish_work,
        now=now,
        resolve_source=_source_resolve(context, loop),
    )
    publication = stage_run.artifacts[0]
    return RevisionPublished(
        publication=publication,
        publication_key=loop.publication_key,
        publication_sha256=publication.content_sha256,
        operation=stage_run.operation,
        stage=stage_run.stage,
        approval=_spent_approval(context, stage_run, approval_id),
    )


def _import_receipt_hash(context: ApplicationContext, loop: LoopOpened) -> str:
    """The hash of the import-receipt manifest file the loop wrote at opening."""
    with store_refusals():
        receipts = list_artifacts(context.store.session, context.task_id)
    for receipt in receipts:
        if receipt.receipt_id == loop.import_artifact_id:
            return receipt.content_sha256
    raise ApplicationRefusedError(
        ApplicationRefusal.ARTIFACT_NOT_FOUND,
        f"the loop's own import receipt {loop.import_artifact_id} is not in the store. "
        "A publication derived from an import that was never recorded derives nothing.",
    )


