def stage_copy(
    context: ApplicationContext,
    loop: LoopOpened,
    *,
    approval_id: ApprovalId,
    run_id: RunId | None = None,
    now: datetime | None = None,
) -> CopyStaged:
    """Write the independent copy the edits are applied to.

    The bytes come from the read-only door, the bytes go through the one write
    point, and the original is re-hashed *inside the authorised effect*: if the
    file moved between the consent and the write, the copy refuses before any
    file is opened and nothing lands.

    :raises ApplicationRefusedError: the approval does not cover this write
        (including the ledger's ``source_changed`` — the original moved after
        the grant), the original drifted, or the write was refused.
    """
    material = SourceMaterial(context.workspace, context.policy)

    def copy_work(resource: CanonicalPath) -> StageOutcome:
        del resource  # the authorised resource is the copy's own key; the bytes come from the door
        verify_original(context, loop)
        data = material.read_permitted(
            loop.import_receipt.source_key,
            root_id=loop.import_receipt.source_root_id,
            capability=CapabilityId.SOURCE_READ.value,
        )
        written = TaskOutputArea(context.workspace).write(loop.copy_key, data)
        return StageOutcome(output_hashes=(written.content_hash,))

    stage_run = run_stage(
        context,
        _stage_request(loop, stage_name=COPY_STAGE_NAME, approval_id=approval_id, run_id=run_id),
        copy_work,
        now=now,
        resolve_source=_source_resolve(context, loop),
    )
    copy_hash = stage_run.stage.output_hashes[0]
    if copy_hash != loop.import_receipt.original_sha256:
        raise ApplicationRefusedError(
            ApplicationRefusal.SOURCE_DRIFTED,
            f"the copy at {loop.copy_key!r} hashed {copy_hash}, not the import "
            f"receipt's {loop.import_receipt.original_sha256}. A copy of an original "
            "that does not match it is a second file wearing the loop's address.",
        )
    return CopyStaged(
        copy_key=loop.copy_key,
        copy_sha256=copy_hash,
        operation=stage_run.operation,
        stage=stage_run.stage,
        approval=_spent_approval(context, stage_run, approval_id),
    )


def _spent_approval(
    context: ApplicationContext, stage_run: StageRun, approval_id: ApprovalId
) -> Approval:
    """The approval as the stage run recorded it, read back when the run did not carry it."""
    carried = stage_run.approval
    if carried is not None:
        return carried
    with store_refusals():
        for approval in list_approvals(context.store.session, context.task_id):
            if approval.approval_id == approval_id:
                return approval
    raise ApplicationRefusedError(
        ApplicationRefusal.APPROVAL_MISSING,
        f"the store holds no approval {approval_id} for this task.",
    )


