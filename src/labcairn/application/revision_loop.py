def _capability_for(stage_name: str) -> CapabilityId:
    if stage_name == COPY_STAGE_NAME:
        return CapabilityId.FS_WRITE
    return CapabilityId.ARTIFACT_WRITE


def _resource_key_for(loop: LoopOpened, stage_name: str) -> str:
    return loop.copy_key if stage_name == COPY_STAGE_NAME else loop.publication_key


def _approval_use(loop: LoopOpened, stage_name: str) -> ApprovalUse:
    """What an approval is spent on: the loop's write, in one spelling.

    The ask and the run build this the same way, from the same two inputs. An
    approval is bound to an *arguments digest*, so two call sites that each
    spelled the arguments out is how an approval and its use drift apart into
    ``args_changed`` refusals that look like a bug in the consent.
    """
    return ApprovalUse(
        capability=_capability_for(stage_name),
        arguments=_loop_arguments(loop, stage_name),
        root_id="output",
        resource_key=_resource_key_for(loop, stage_name),
        depends_on=(loop.import_receipt.original_sha256,),
    )


def _stage_request(
    loop: LoopOpened,
    *,
    stage_name: str,
    approval_id: ApprovalId | None,
    run_id: RunId | None,
) -> StageRequest:
    """The stage request for one effect, built from the same use the approval covers."""
    use = _approval_use(loop, stage_name)
    return StageRequest(
        stage_name=stage_name,
        capability=use.capability,
        arguments=use.arguments,
        root_id=use.root_id,
        resource_key=use.resource_key,
        run_id=run_id,
        approval_id=approval_id,
        depends_on=use.depends_on,
    )


def _current_original_hash(context: ApplicationContext, loop: LoopOpened) -> str:
    """The original's hash right now, through the read-only door."""
    material = SourceMaterial(context.workspace, context.policy)
    receipt = loop.import_receipt
    return material.hash_of(receipt.source_key, root_id=receipt.source_root_id)


def _source_resolve(context: ApplicationContext, loop: LoopOpened) -> Callable[[str], Path]:
    """Resolve a bound source key the way the loop named it: in its source root.

    The generic spend resolves bound sources against the root the *resource*
    lives in — which for the loop's writes is the output root, and the original
    is not there. Resolving the original against the output root would hash a
    different file, or fail to find one, and ``SOURCE_CHANGED`` would be
    reported for material that never moved. The loop knows which root its
    material lives in, so it says so.
    """
    root_id = loop.import_receipt.source_root_id
    return lambda key: context.workspace.path_in(key, root_id).real_path


def request_loop_approval(
    context: ApplicationContext,
    loop: LoopOpened,
    *,
    stage_name: str,
    expires_at: datetime,
    run_id: RunId | None = None,
    now: datetime | None = None,
) -> ApprovalRequested:
    """Ask for one loop effect's consent, **with the original bound to it**.

    ``bound_sources`` is the half the generic approval path left empty until
    this ticket: the hash is minted from the original *as it is at the ask*,
    recorded on the approval row, and re-hashed at the spend. A consent bound
    to no source is a consent about an abstraction; this one is about a file.
    """
    binding = SourceBinding(
        resource_key=loop.import_receipt.source_key,
        expected_hash=_current_original_hash(context, loop),
    )
    return request_approval(
        context,
        ApprovalRequest(
            use=_approval_use(loop, stage_name),
            expires_at=expires_at,
            run_id=run_id,
            stage_name=stage_name,
            bound_sources=(binding,),
        ),
        now=now,
    )


def verify_original(context: ApplicationContext, loop: LoopOpened) -> str:
    """Re-hash the original and compare it with the import receipt.

    Public because it is the claim the loop is built on: *the original is
    unchanged through the loop* is a comparison someone runs, and a surface
    that cannot run it can only restate it.

    :raises ApplicationRefusedError: ``source_drifted`` when the bytes moved.
    """
    current = _current_original_hash(context, loop)
    if current != loop.import_receipt.original_sha256:
        raise ApplicationRefusedError(
            ApplicationRefusal.SOURCE_DRIFTED,
            f"the original {loop.import_receipt.relative_path!r} is no longer the bytes "
            f"the import receipt hashed ({current} != "
            f"{loop.import_receipt.original_sha256}). Nothing is copied, published or "
            "overwritten: the loop's derivations would name a file that no longer "
            "exists as recorded.",
        )
    return current


