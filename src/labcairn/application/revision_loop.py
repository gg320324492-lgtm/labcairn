"""One revision loop: import, independent copy, publication, recovery.

LC-P3-03's deliverable is not any of the parts — the read-only door
(:mod:`labcairn.workspace.readonly`), the single write point
(:mod:`labcairn.workspace.outputs`), the approval binding
(:mod:`labcairn.security.approval`) and the reconciliation branch
(:mod:`labcairn.recovery`) all existed before this module. What did not exist
is **one loop that binds them**: a project-scoped import receipt that carries
the original's content hash, an independent copy the edits are applied to, a
publication receipt derived from that hash, and a recovery path that resolves
an interrupted publication instead of replanning it.

The loop's three effects, and what each one is authorised against
-----------------------------------------------------------------

* **import** reads the original through the read-only door
  (:meth:`SourceMaterial.read_permitted`), records the material in the ledger,
  binds it to the task, and writes the **import receipt** — a manifest in the
  task output area plus a ``MANIFEST`` artefact row whose derivation names the
  original file and carries its hash. Everything downstream is checked against
  that hash.
* **copy** spends one approval and writes an **independent copy** of the
  original's bytes into the task output area. The approval is bound to the
  original's hash at grant time (``bound_sources``, minted by
  :func:`labcairn.application.approvals.request_approval` since this ticket)
  and re-hashed at the spend: whoever could restate the binding at the moment
  of use could authorise a copy of different bytes.
* **publish** spends a second approval and writes the edited bytes at a fixed
  key, recording the **publication receipt** — an artefact row derived from
  the original's hash *and* from the import receipt. Before the write, the
  original on disk is re-hashed and compared with the import receipt: an
  original that moved during the loop makes the derivation false, and a false
  derivation is refused rather than recorded.

Why the copy and the publication are separate writes
----------------------------------------------------

The copy is the file an edit is applied *to*; the publication is the copy's
final state. Keeping them apart is what makes the recovery question answerable:
a crash after the copy leaves the loop re-runnable, and a crash after the
publication write but before its confirmation is the one case a **probe** can
resolve — the predicted bytes are on disk, the effect landed, and the same
publication id replayed lands one artefact row, not two
(:meth:`TaskOutputArea.write` is atomic, and the artefact row is upserted by
its id).

What the loop refuses, and before what
-------------------------------------

The four refusal classes the work order names are refused **before any file is
touched**, each witnessed against real files in
``tests/test_revision_loop_refusals.py``:

* **cross-project access** — a source key that resolves into a task output
  area (another task's generated bytes) is refused as ``cross_project_access``
  before the file is read;
* **path escape** — a key the canonicaliser will not admit (a traversal out of
  every bound root) is refused as ``path_refused``;
* **stale approval** — the original's bytes moved between the grant and the
  spend: the ledger's re-hash catches it (``SOURCE_CHANGED`` →
  ``approval_refused``) and nothing is written;
* **duplicate requests** — one approval cannot spend twice
  (``approval_missing``), and a publication id that already carries a receipt
  is refused as ``loop_already_published`` **before the second write opens**.

ADR-0021's temporary independent copy
-------------------------------------
``src/labcairn/editing/evidence.py`` copies a manuscript's bytes to a directory
the caller names — a labelled *temporary* mechanism for the fidelity experiment.
This module is the product mechanism it was waiting for: the copy lives in the
task output area, is written by the same atomic write point everything else
uses, and its whole existence is authorised. What happened to the temporary
mechanism at this landing is stated in
``docs/acceptance/LC-P3-03-revision-loop-2026-11-10.md`` (§14 item 6's ruling:
the disposition lives there, not in ADR-0021's text).
"""

