#: The loop's directory name inside the task output area. One directory per
#: loop, named by the import receipt's id, so the copy, the candidate and the
#: publication of one revision are one addressable group. Keys in this module
#: are **output-root-relative** — the spelling :class:`TaskOutputArea` and
#: :class:`StageRequest` address by.
LOOP_DIR_NAME = "revisions"

#: The stage names the loop's two approval-gated effects run under. The
#: receipt id is carried in the loop directory, not the stage name, so a retry
#: of one loop is the same stage and two loops in one run are two stages that
#: cannot be confused.
COPY_STAGE_NAME = "revision-copy"
PUBLICATION_STAGE_NAME = "revision-publication"

#: The producer the loop's receipts name. A receipt whose producer is a bare
#: "tool" names nobody; this names the module that wrote the bytes.
LOOP_PRODUCER_ID = "labcairn.application.revision_loop"


# --------------------------------------------------------------------------- #
# the loop's own records
# --------------------------------------------------------------------------- #


class ImportReceipt(Result):
    """What the loop imported, and the hash everything is checked against.

    ``original_sha256`` is the load-bearing field. The copy's approval binding,
    the publication's derivation and the publish-time guard all compare against
    it, which is what turns "the original is unchanged through the loop" from
    an intention into a checked claim.
    """

    receipt_id: str
    task_id: str
    source_id: str
    source_root_id: str
    #: The key as the source root names it — the spelling the approval's
    #: re-hash resolves, not the workspace-relative one the ledger stores.
    source_key: str
    #: Workspace-relative, POSIX-separated: the spelling the ledger's ``Source``
    #: row and the publication's derivation use.
    relative_path: str
    original_sha256: str
    size_bytes: int
    imported_at: datetime


class LoopOpened(Result):
    """An opened loop: its receipt, and the fixed addresses its effects write to.

    ``publication_artifact_id`` is minted **at opening** rather than at
    publication. That is what makes a replayed publication land one artefact
    row: the id is carried in the publication approval's digest, so a retry
    authorised by a fresh approval still names the same row, and the row is
    upserted by its id.
    """

    import_receipt: ImportReceipt
    copy_key: str
    publication_key: str
    manifest_key: str
    publication_artifact_id: str
    import_artifact_id: str


class CopyStaged(Result):
    """The independent copy, landed.

    ``copy_sha256`` equals the import receipt's ``original_sha256`` — that
    equality is witnessed, not assumed: a copy that hashed differently than
    the original it claims to copy is a copy of something else.
    """

    copy_key: str
    copy_sha256: str
    operation: Operation
    stage: Stage
    approval: Approval


class RevisionPublished(Result):
    """What publishing produced: the receipt, the landed bytes, the records."""

    publication: ArtifactReceipt
    publication_key: str
    publication_sha256: str
    operation: Operation
    stage: Stage
    approval: Approval


def _loop_dir(loop: LoopOpened) -> str:
    return f"{LOOP_DIR_NAME}/{loop.import_receipt.receipt_id}"


def _loop_arguments(loop: LoopOpened, stage_name: str) -> dict[str, Any]:
    if stage_name == COPY_STAGE_NAME:
        return {"path": loop.copy_key}
    return {"path": loop.publication_key, "artifact_id": loop.publication_artifact_id}


