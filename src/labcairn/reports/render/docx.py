"""The DOCX form: the editable form, and python-docx's writer over the model.

ADR-0013 chose python-docx for this form and rejected the alternatives for
reasons that are not about taste. A DOCX is an OOXML package with a styles
part, a numbering part and a relationships graph, and the work order asks
for a *"basic editable DOCX"* — editable, which is the whole point of the
format. Hand-writing that surface is the improvisation the ADR refused;
python-docx is MIT, its only other dependency is lxml, and it embeds no
font, so the report's appearance in Word depends on the reader's installed
fonts and on nothing else.

**The library is imported lazily.** ADR-0013's constraint 2: a report
exported only as Markdown must not load lxml. So the import is inside the
function, and the Markdown and HTML paths pay nothing for the DOCX form.

**The document's own properties are set, because the defaults are false
statements.** python-docx's template says its author is ``python-docx``,
that its description is ``generated by python-docx``, and that it was
created in 2013. A report that says it was written by a library is a false
statement about who produced it, and ADR-0013's constraint 6 requires the
author, the title and the description to be set explicitly. The creation
and modification dates are set to the moment the report is a view of,
which is a value the model holds — the alternative was a report dated 2013.
**The moment is converted to UTC first**, because the format python-docx
writes is a UTC one and it does not apply the offset: it writes
``strftime('%Y-%m-%dT%H:%M:%SZ')``, which is the wall-clock time of
whatever it is given with a ``Z`` bolted on. A moment that is aware and
not in UTC would therefore be written as its **local** time, and the
``Z`` would be hours wrong.

**The bytes are not reproducible, and the exporter does not pretend
otherwise.** A DOCX is a ZIP, and every one of its seventeen entries
carries the timestamp of the moment it was written. The owner's decision
of 2026-10-20 was that the report's reproducible forms are Markdown and
HTML and that the DOCX's bytes are recorded but not claimed reproducible
(the breakdown's §1.4.3, Option A), and the exporter therefore does not
reach into the container metadata to pin it. Pinning the ZIP timestamps
was measured to be possible and was declined: it would make the export
lie about when it was made, in exchange for a hash comparison nobody asked
for.

The module is named after the form it writes, so ``import docx`` below is
the library's: Python 3 imports absolutely, and an installed package
precedes the module that shares its name.
"""

from __future__ import annotations

import io
from datetime import UTC, datetime
from typing import TYPE_CHECKING

from labcairn.reports.model import BlockKind, ReportDocument
from labcairn.reports.render.constants import (
    FIRST_PASS_NOTICE,
    REPRODUCIBILITY_NOTICE,
)
from labcairn.reports.render.resolve import (
    ReportItem,
    resolve,
    with_interpretation_marker,
)

if TYPE_CHECKING:
    from docx.document import Document

__all__ = ["render_docx"]


def render_docx(document: ReportDocument) -> bytes:
    """The report as a DOCX.

    :param document: the report's model, frozen at one moment.
    :returns: the DOCX's bytes. They are **not** byte-reproducible: a DOCX
        is a ZIP and its entries carry the time the file was written. The
        **document's** dates are the moment the report is a view of, in
        UTC — see :func:`_in_utc` for why the conversion is the writer's
        business and not the reader's.
    """
    try:
        import docx
    except ImportError as exc:
        raise RuntimeError(
            "python-docx is required to write a DOCX; it is a declared dependency"
        ) from exc

    report = resolve(document)
    word = docx.Document()

    core = word.core_properties
    core.author = "LabCairn"
    core.title = report.title
    # python-docx spells the ``dc:description`` field ``comments``. The
    # default says "generated by python-docx", which is a false statement
    # about who produced the report, so it is replaced by the limit the
    # report states on its own face.
    core.comments = FIRST_PASS_NOTICE
    core.created = _in_utc(report.as_of)
    core.modified = _in_utc(report.as_of)

    word.add_heading(report.title, level=0)
    word.add_paragraph(FIRST_PASS_NOTICE)
    word.add_paragraph(REPRODUCIBILITY_NOTICE)
    word.add_paragraph(f"Snapshot: {report.as_of.isoformat()}")
    if report.record_ids:
        word.add_paragraph(f"Records: {', '.join(report.record_ids)}")

    for section in report.sections:
        word.add_heading(section.heading, level=1)
        for item in section.items:
            _add_item(word, item)

    if report.unplaced_figures or report.unplaced_tables:
        word.add_heading("Artefacts not placed in a section", level=1)
        unplaced: tuple[ReportItem, ...] = (*report.unplaced_figures, *report.unplaced_tables)
        for item in unplaced:
            _add_item(word, item)

    word.add_heading("Provenance", level=1)
    for footnote in report.footnotes:
        for line in footnote.lines:
            word.add_paragraph(line, style="List Bullet")

    buffer = io.BytesIO()
    word.save(buffer)
    return buffer.getvalue()


def _in_utc(moment: datetime) -> datetime:
    """The moment in UTC, because the format the DOCX uses is a UTC one.

    python-docx writes the creation and modification dates with
    ``strftime('%Y-%m-%dT%H:%M:%SZ')``: the wall-clock time of whatever
    datetime it is given, with a ``Z`` bolted on. The offset is **dropped**,
    not applied, so a moment that is aware and not in UTC would be written
    as its local time and the ``Z`` would be hours wrong — ``12:00+08:00``
    recorded as ``12:00Z`` is eight hours after the fact.

    The moment is converted to UTC first, and the ``Z`` is then true. The
    model's moment is always aware, so the conversion is a conversion and
    not a guess.
    """
    return moment.astimezone(UTC)


def _add_item(word: Document, item: ReportItem) -> None:
    """Write one resolved block into the document.

    The wording is the item's own, so the DOCX says what the Markdown and
    the HTML and the PDF say. The shape is the renderer's: a finding and a
    disclosure are bullets, because they are entries in a list, and a
    narrative is a paragraph, because it is prose.
    """
    lines = with_interpretation_marker(item.lines, item.is_interpretation)
    style = "List Bullet" if item.kind in (BlockKind.CLAIM, BlockKind.UNRESOLVED) else None
    for line in lines:
        word.add_paragraph(line, style=style)
